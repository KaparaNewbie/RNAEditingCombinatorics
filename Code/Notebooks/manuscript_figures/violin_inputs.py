"""Recover original display contours, while computing summaries from native tables.

SVGs are generated by the named original notebook plotting cells. They preserve
historical KDE shapes/jitter; scientific values never come from rounded pixels.
"""
from pathlib import Path
import io
import json
import re
import xml.etree.ElementTree as ET
import numpy as np
import pandas as pd
from scipy.optimize import linprog
from .styles import GENE_COLORS

NS = {'s': 'http://www.w3.org/2000/svg'}


def _native_noise_columns(path):
    """Project scalar fields before parsing rows containing long read-ID lists."""
    projected = io.StringIO()
    with Path(path).open() as source:
        header = source.readline().rstrip('\n').split('\t')
        indices = [header.index(name) for name in ['Gene', '%Noise']]
        projected.write('Gene\t%Noise\n')
        for line in source:
            fields = line.rstrip('\n').split('\t')
            assert len(fields) == len(header)
            projected.write('\t'.join(fields[i] for i in indices) + '\n')
    projected.seek(0)
    return pd.read_table(projected)


def s1_noise_geometry(notebook_dir, svg_path, output_dir, *, noise_table=None):
    """One noise observation is one native non-editing position in a target gene."""
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    assert not any((output_dir / name).exists() for name in ["figure_s1_noise.tsv", "figure_s1_violin_geometry.json"])
    groups = [g for g in ET.parse(svg_path).iter() if g.get('class', '').startswith('trace violins')]
    assert len(groups) == 21
    tables, geometry = [], []
    cached = pd.read_table(noise_table, float_precision='round_trip') if noise_table is not None else None
    for platform in ['PacBio', 'Illumina']:
        data = (_native_noise_columns(Path(notebook_dir) / f'NoiseLevels.{platform}.tsv')
            if cached is None else cached.loc[cached.Platform.eq(platform)].rename(columns={'PercentNoise': '%Noise'}))
        data.Gene = data.Gene.str.split('_').str[0].replace({'GRIA': 'GRIA2'})
        order = ['GRIA2', 'PCLO'] if platform == 'PacBio' else ['PCLO'] + sorted(set(data.Gene)-{'PCLO'})
        for gene in order:
            values = data.loc[data.Gene.eq(gene), '%Noise'].to_numpy()
            trace = len(tables)
            tables.append(pd.DataFrame({'Trace': trace, 'Platform': platform, 'Gene': gene,
                'Observation': np.arange(len(values)), 'PercentNoise': values}))
            group = groups[trace]
            path = group.find('s:path', NS)
            points = group.findall('s:g/s:path', NS)
            ys = [float(re.search(r'translate\([^,]+,([\d.]+)\)', p.get('transform'))[1]) for p in points]
            q1, q3 = np.quantile(values, [.25, .75], method='hazen')
            outliers = np.sort(values[(values < q1-1.5*(q3-q1)) | (values > q3+1.5*(q3-q1))])
            np.testing.assert_allclose(270-30*outliers, ys, rtol=0, atol=.00501)
            geometry.append({'trace': trace, 'd': path.get('d'), 'outlier_y_px': ys,
                'outlier_values': outliers.tolist(), 'quartiles': [q1, q3],
                'plot_width_px': 60.01311475409836 if platform == 'PacBio' else 570.1245901639344,
                'height_px': 270, 'ylim': [0, 9]})
    pd.concat(tables, ignore_index=True).to_csv(output_dir / 'figure_s1_noise.tsv', sep='\t', index=False, mode='x')
    (output_dir / 'figure_s1_violin_geometry.json').write_text(json.dumps(geometry))
    return geometry


def s17_statistics_geometry(observations_path, svg_paths, output_dir):
    """Selected isoform means from original direct support; no reassigned-read mean."""
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=False)
    observations = pd.read_table(observations_path, usecols=['Platform', 'Gene', 'Facet', 'Abundancy', 'MeanEditedPositions'], float_precision='round_trip')
    statistics, geometry = [], []
    for platform, svg_path in zip(['Long-reads', 'Short-reads'], svg_paths, strict=True):
        root = ET.parse(svg_path)
        groups = [g for g in root.iter() if g.get('class', '').startswith('trace violins')]
        width = float(root.findall('.//s:clipPath/s:rect', NS)[0].get('width'))
        height = float(root.findall('.//s:clipPath/s:rect', NS)[0].get('height'))
        subset = observations.loc[observations.Platform.eq(platform)]
        facets = list(subset.groupby(['Facet', 'Gene'], sort=False))
        assert len(groups) == len(facets)
        scientific, pixels = [], []
        start = len(geometry)
        for ((facet, gene), data), group in zip(facets, groups, strict=True):
            for category, label in enumerate(['1% most expressed', '30% least expressed']):
                values = data.loc[data.Abundancy.eq(label), 'MeanEditedPositions'].to_numpy()
                assert np.isfinite(values).all()
                q1, median, q3 = np.quantile(values, [.25, .5, .75], method='hazen')
                inliers = values[(values >= q1-1.5*(q3-q1)) & (values <= q3+1.5*(q3-q1))]
                low, high = inliers.min(), inliers.max()
                outliers = np.sort(values[(values < low) | (values > high)])
                box = group.findall('s:path[@class="box"]', NS)[category].get('d')
                numbers = list(map(float, re.findall(r'[-\d.]+', box)))
                mean = group.findall('s:path[@class="mean"]', NS)[category].get('d')
                mean_pixel = float(re.search(r'M[^,]+,([-\d.]+)', mean)[1])
                points = group.findall('s:g[@class="points"]', NS)[category].findall('s:path', NS)
                point_y = [float(re.search(r'translate\([^,]+,([-\d.]+)\)', p.get('transform'))[1]) for p in points]
                assert len(outliers) == len(point_y)
                scientific.extend([median, q1, q3, low, high, values.mean(), *outliers])
                pixels.extend([*[numbers[i] for i in [1, 4, 6, 10, 13]], mean_pixel, *point_y])
                statistics.append({'Platform': platform, 'Gene': gene, 'Facet': facet, 'Category': category,
                    'Abundancy': label, 'N': len(values), 'Mean': values.mean(), 'Q1': q1, 'Median': median,
                    'Q3': q3, 'WhiskerLow': low, 'WhiskerHigh': high, 'Color': GENE_COLORS[gene]})
                geometry.append({'Platform': platform, 'Gene': gene, 'Facet': facet, 'Category': category,
                    'path': group.findall('s:path[@class="violin"]', NS)[category].get('d'),
                    'outliers': outliers.tolist(), 'width_px': width, 'height_px': height})
        a = np.column_stack([scientific, np.ones(len(scientific))])
        b, tolerance = np.array(pixels), .005001
        fit = linprog([0, 0], A_ub=np.vstack([a, -a]), b_ub=np.r_[b+tolerance, -b+tolerance],
            bounds=[(None, None), (None, None)], method='highs')
        assert fit.success, (platform, 'Native statistics disagree with original vector coordinates')
        for record in geometry[start:]: record['y_scale'], record['y_offset'] = fit.x.tolist()
    table = pd.DataFrame(statistics)
    table.to_csv(output_dir / 'figure_s17_statistics.tsv', sep='\t', index=False, mode='x')
    (output_dir / 'figure_s17_geometry.json').write_text(json.dumps(geometry))
    return table, geometry
